"""Sieve engine for matching and deduplication."""

from collections.abc import Iterable
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

from beancount import loader
from beancount.core.amount import Amount
from beancount.core.convert import get_weight
from beancount.core.data import Directive, Posting, TxnPosting
from beancount.core.data import Transaction as BeanTransaction

from .metadata_keys import REBATE_TOPUP_MATCH
from .types import MatchDiagnostic, MatchResult, MetaDiagnostic, Transaction


@dataclass
class SieveConfig:
    """Configuration for the Sieve engine."""

    date_tolerance: int = 2  # days
    amount_tolerance: Decimal = Decimal("0.01")
    # Accounts whose postings count as rebate income in the gross-amount match;
    # see _is_rebate_account for how each entry is read.
    rebate_account_prefixes: tuple[str, ...] = ("Income:Rebate:",)


class Sieve:
    """
    Matching engine for reconciling statement transactions with ledger entries.

    Implements fuzzy matching with configurable tolerances.
    """

    def __init__(self, config: SieveConfig | None = None):
        self.config = config or SieveConfig()
        self._ledger_entries: list[TxnPosting] = []
        self._ledger_index: dict[tuple, list[TxnPosting]] = {}
        self._rebate_index: dict[tuple, list[TxnPosting]] = {}
        self._postings_by_txn: dict[int, list[TxnPosting]] = {}
        self._rebate_sums: dict[int, dict[str, Decimal]] = {}

    def load_ledger(
        self,
        path: Path,
        account_filter: str | None = None,
        date_range: tuple[date, date] | None = None,
    ) -> None:
        """
        Load Beancount ledger and build index for matching.

        Args:
            path: Path to main beancount file or directory
            account_filter: Only include transactions with this account prefix
            date_range: Only include transactions within this range
        """
        if path.is_dir():
            # Find main.bean or *.bean files
            main_file = path / "main.bean"
            if not main_file.exists():
                bean_files = list(path.glob("*.bean"))
                if not bean_files:
                    raise ValueError(f"No .bean files found in {path}")
                main_file = bean_files[0]
            path = main_file

        entries, errors, options = loader.load_file(str(path))

        if errors:
            # Log errors but continue
            for error in errors[:5]:  # limit error output
                print(f"Warning: {error}")

        self._process_entries(entries, account_filter, date_range)

    def _process_entries(
        self,
        entries: list[Directive],
        account_filter: str | None,
        date_range: tuple[date, date] | None,
    ) -> None:
        """Process ledger entries and build matching index."""
        self._ledger_entries = []
        self._ledger_index = {}
        self._rebate_index = {}
        self._postings_by_txn = {}
        self._rebate_sums = {}

        for entry in entries:
            if not isinstance(entry, BeanTransaction):
                continue

            # Skip padding transactions (auto-generated by Beancount, flag='P')
            if entry.flag == "P":
                continue

            # Date filter
            if date_range and (
                entry.date < date_range[0] or entry.date > date_range[1]
            ):
                continue

            rebate_sums = {
                currency: total
                for currency, total in _rebate_sums(
                    entry, self.config.rebate_account_prefixes
                ).items()
                if total > 0
            }
            if rebate_sums:
                self._rebate_sums[id(entry)] = rebate_sums

            # Process postings - only Asset/Liability accounts (cash flow side)
            for posting in entry.postings:
                if account_filter and not posting.account.startswith(account_filter):
                    continue

                # Only match against Asset/Liability postings (not Expense/Income)
                # Bank statements represent cash flow, which appears on balance sheet accounts
                if not (
                    posting.account.startswith("Assets:")
                    or posting.account.startswith("Liabilities:")
                ):
                    continue

                txn_posting = TxnPosting(entry, posting)
                self._ledger_entries.append(txn_posting)
                self._postings_by_txn.setdefault(id(entry), []).append(txn_posting)

                # Build index for fast lookup
                # Index by (date, abs_amount) for fuzzy matching
                if posting.units and posting.units.number is not None:
                    key = (entry.date, abs(posting.units.number))
                    if key not in self._ledger_index:
                        self._ledger_index[key] = []
                    self._ledger_index[key].append(txn_posting)

                    # Also index by total cost if there's a price (e.g., -14 USD @@ 98 CNY)
                    # This allows matching statement CNY amount to ledger USD posting
                    if posting.price and posting.price.number is not None:
                        total_cost = abs(posting.units.number * posting.price.number)
                        cost_key = (entry.date, total_cost.quantize(Decimal("0.01")))
                        if cost_key not in self._ledger_index:
                            self._ledger_index[cost_key] = []
                        self._ledger_index[cost_key].append(txn_posting)

                    # A statement row that reports the gross amount of a
                    # rebate-funded payment finds the fund leg under the sum.
                    rebate = rebate_sums.get(posting.units.currency)
                    if rebate:
                        gross_key = (entry.date, abs(posting.units.number) + rebate)
                        self._rebate_index.setdefault(gross_key, []).append(txn_posting)

    def match(
        self,
        transactions: Iterable[Transaction],
        covered_accounts: list[str] | None = None,
        covered_ranges: dict[str, list[tuple[date, date]]] | None = None,
        covered_groups: list[set[str]] | None = None,
        meta_check: bool = True,
        ambiguous_check: bool = True,
    ) -> MatchResult:
        """
        Match statement transactions against loaded ledger entries.

        When meta_check=True (default), card_last4 is a soft check: matches still
        succeed on date/amount/payee, but mismatches or missing metadata surface
        as MetaDiagnostic entries. When meta_check=False, card_last4 acts as a
        hard filter (legacy behavior).

        Args:
            transactions: Statement transactions to match
            covered_accounts: Optional list of accounts to consider for Extra calculation.
                If provided, only unmatched ledger entries in these accounts are reported
                as Extra. If None, all unmatched entries are reported.
            covered_ranges: Optional dict mapping account to list of (start, end) date
                ranges. An account listed here yields Extra entries only within its
                ranges; an account absent from it keeps every unmatched entry.
            covered_groups: Optional sets of accounts that one statement speaks for
                as a whole. An unmatched posting in the same group as a matched
                sibling it offsets is exempt from Extra (see
                _settled_transfer_legs). If None, covered_accounts forms the
                single group (every account when covered_accounts is also None).
            meta_check: When True (default), card_last4 is a soft check producing
                MetaDiagnostic entries. When False, card_last4 hard-filters matches.
            ambiguous_check: When True (default), matches with multiple viable
                candidates from different ledger transactions surface as
                MatchDiagnostic entries.

        Returns:
            MatchResult with matched pairs, missing, extra transactions, and
            meta/match diagnostics.
        """
        transactions = list(transactions)
        matched: list[tuple[Transaction, TxnPosting]] = []
        missing: list[Transaction] = []
        diagnostics: list[MetaDiagnostic] = []
        match_diagnostics: list[MatchDiagnostic] = []
        used_ledger_entries: set[int] = set()

        # A rebate top-up row can also fall back to the rebate sums, so it
        # picks after every exact-only row has taken its posting; the results
        # are reported in statement order regardless.
        order = sorted(
            range(len(transactions)),
            key=lambda i: _has_gross_fallback(transactions[i]),
        )
        found: list[tuple[TxnPosting | None, int]] = [(None, 0)] * len(transactions)
        # Matching a priced posting by its cost is a fallback for statements
        # that cannot show the units currency. It runs once every row had its
        # chance at a units match, so an exchange leg's cost never takes the
        # posting a same-sized payment in the price currency was booked to.
        for by_cost in (False, True):
            for i in order:
                if found[i][0] is not None:
                    continue
                match, n_others = self._find_match(
                    transactions[i],
                    used_ledger_entries,
                    meta_check=meta_check,
                    ambiguous_check=ambiguous_check,
                    by_cost=by_cost,
                )
                found[i] = (match, n_others)
                if match:
                    used_ledger_entries.add(id(match))

        for txn, (match, n_others) in zip(transactions, found, strict=True):
            if match:
                matched.append((txn, match))
                if meta_check:
                    diag = self._diagnose_meta(txn, match)
                    if diag is not None:
                        diagnostics.append(diag)
                if n_others:
                    match_diagnostics.append(
                        self._diagnose_ambiguous(txn, match, n_others)
                    )
            else:
                missing.append(txn)

        exempt = self._settled_transfer_legs(
            [entry for _, entry in matched],
            used_ledger_entries,
            covered_accounts,
            covered_groups,
        )

        extra = []
        for entry in self._ledger_entries:
            if id(entry) in used_ledger_entries or id(entry) in exempt:
                continue
            # Filter by covered accounts
            if (
                covered_accounts is not None
                and entry.posting.account not in covered_accounts
            ):
                continue
            # Filter by covered ranges
            if covered_ranges is not None:
                account = entry.posting.account
                entry_date = entry.txn.date
                # Skip if account has covered ranges but date is not within any range
                if account in covered_ranges and not self._in_covered_range(
                    account, entry_date, covered_ranges
                ):
                    continue
            extra.append(entry)

        return MatchResult(
            matched=matched,
            missing=missing,
            extra=extra,
            meta_diagnostics=diagnostics,
            match_diagnostics=match_diagnostics,
        )

    def _settled_transfer_legs(
        self,
        matched: list[TxnPosting],
        used: set[int],
        covered_accounts: list[str] | None,
        covered_groups: list[set[str]] | None,
    ) -> set[int]:
        """Return ids of unmatched postings settled by a matched sibling leg.

        A transfer between two accounts of one statement-wide provider shows up
        as a single statement row, which consumes one leg; that same row also
        accounts for the opposite leg. One row settles one two-sided transfer,
        so each matched leg pairs with at most one opposite leg. The two legs
        of a currency exchange or a `{}` lot trade offset each other in the
        price or cost currency, and a fee or rebate booked beside such a
        conversion closes the gap between the two legs.
        """
        if covered_groups is None and covered_accounts is not None:
            covered_groups = [set(covered_accounts)]

        def same_group(a: str, b: str) -> bool:
            if covered_groups is None:
                return True
            return any(a in group and b in group for group in covered_groups)

        tolerance = self.config.amount_tolerance

        def offsets(
            leg: dict[str, Decimal],
            sibling: dict[str, Decimal],
            charges: dict[str, Decimal],
        ) -> bool:
            for currency in leg.keys() & sibling.keys():
                # Opposite signs keep a split payment's second funding leg out:
                # its transaction balances through the expense just as well.
                if leg[currency] * sibling[currency] >= 0:
                    continue
                net = leg[currency] + sibling[currency]
                charge = charges.get(currency, Decimal(0))
                if abs(net) <= tolerance or abs(net + charge) <= tolerance:
                    return True
            return False

        exempt: set[int] = set()
        for leg in matched:
            leg_amounts = _amounts_by_currency(leg.posting)
            if not leg_amounts:
                continue
            charges = _income_statement_sums(leg.txn)
            leg_currency = _balance_key(leg.posting)[1]
            for sibling in self._postings_by_txn[id(leg.txn)]:
                posting = sibling.posting
                # Only a conversion tells a fee or rebate apart: between two
                # legs of one currency an expense of any size balances the
                # transaction, purchase or fee alike.
                converts = _balance_key(posting)[1] != leg_currency
                if (
                    id(sibling) in used
                    or id(sibling) in exempt
                    or _balance_key(posting) == _balance_key(leg.posting)
                    or not same_group(posting.account, leg.posting.account)
                    or not offsets(
                        leg_amounts,
                        _amounts_by_currency(posting),
                        charges if converts else {},
                    )
                ):
                    continue
                exempt.add(id(sibling))
                break
        return exempt

    def _in_covered_range(
        self,
        account: str,
        entry_date: date,
        covered_ranges: dict[str, list[tuple[date, date]]],
    ) -> bool:
        """Check if account+date falls within any covered range."""
        if account not in covered_ranges:
            return False
        return any(start <= entry_date <= end for start, end in covered_ranges[account])

    def _find_match(
        self,
        txn: Transaction,
        used: set[int],
        meta_check: bool = True,
        ambiguous_check: bool = True,
        by_cost: bool = False,
    ) -> tuple[TxnPosting | None, int]:
        """Find a matching ledger entry for the given transaction.

        Returns the chosen match (or None) and the number of other viable
        candidates belonging to *different* ledger transactions. A non-zero
        count means the greedy pick was ambiguous.

        Ambiguity is only reported when the transaction has no target account
        (nothing to disambiguate with). When it is constrained to an account,
        multiple same-amount postings on that account pair up 1:1 and the pick
        is harmless, so the first match short-circuits and the count is 0.
        """
        # First try exact order_id match if available. order_id is a strong
        # key, so an order_id match is never treated as ambiguous.
        if txn.order_id:
            for entry in self._ledger_entries:
                if id(entry) in used:
                    continue
                if self._match_by_order_id(txn, entry):
                    return entry, 0

        # A flagged gross row tries the rebate sums only after every exact
        # candidate failed: an exact posting is the stronger evidence, and the
        # same-amount statement row it would otherwise steal has no fallback.
        tiers = (False, True) if _has_gross_fallback(txn) else (False,)
        for gross in tiers:
            chosen, n_others = self._pick(
                txn, used, meta_check, ambiguous_check, gross=gross, by_cost=by_cost
            )
            if chosen is not None:
                return chosen, n_others
        return None, 0

    def _pick(
        self,
        txn: Transaction,
        used: set[int],
        meta_check: bool,
        ambiguous_check: bool,
        gross: bool,
        by_cost: bool = False,
    ) -> tuple[TxnPosting | None, int]:
        candidates = (
            candidate
            for candidate in self._get_candidates(txn, gross=gross)
            if id(candidate) not in used
            and self._is_match(
                txn, candidate, meta_check=meta_check, gross=gross, by_cost=by_cost
            )
        )
        # Only scan all candidates to detect ambiguity for unconstrained
        # transactions; otherwise stop at the first match.
        if not (ambiguous_check and txn.account is None):
            return next(candidates, None), 0

        viable = list(candidates)
        if not viable:
            return None, 0

        chosen = viable[0]
        # Only count candidates from a different ledger transaction as
        # ambiguous; multiple postings of the same entry are not a conflict.
        n_others = sum(1 for c in viable[1:] if c.txn is not chosen.txn)
        return chosen, n_others

    def _get_candidates(
        self, txn: Transaction, gross: bool = False
    ) -> list[TxnPosting]:
        """Get candidate ledger entries for matching."""
        index = self._rebate_index if gross else self._ledger_index
        candidates = []
        # Exact amount first, so a posting at the statement amount wins over a
        # fallback amount on any date within tolerance.
        amounts = [abs(txn.amount)]
        for fallback in (txn.original_amount, _net_of_fee(txn)):
            if fallback is not None and fallback not in amounts:
                amounts.append(fallback)

        for amount in amounts:
            for delta in range(self.config.date_tolerance + 1):
                for sign in [0, 1, -1]:
                    if delta == 0 and sign != 0:
                        continue
                    check_date = txn.date + timedelta(days=delta * sign if sign else 0)
                    candidates.extend(index.get((check_date, amount), []))

        return candidates

    def _match_by_order_id(self, txn: Transaction, entry: TxnPosting) -> bool:
        """Check if order_id matches in entry metadata."""
        if not txn.order_id:
            return False

        meta = entry.txn.meta
        return meta.get("order_id") == txn.order_id

    def _is_match(
        self,
        txn: Transaction,
        entry: TxnPosting,
        meta_check: bool = True,
        gross: bool = False,
        by_cost: bool = False,
    ) -> bool:
        """Check if transaction matches ledger entry.

        With ``gross``, the amount must equal the posting plus its transaction's
        rebates instead of the posting itself. With ``by_cost``, a priced
        posting also matches at its total price.
        """
        posting = entry.posting
        bean_txn = entry.txn

        # Account constraint: if transaction has a target account, must match exactly
        if txn.account and posting.account != txn.account:
            return False

        # Amount must match (with tolerance)
        if posting.units and posting.units.number is not None:
            units_number = posting.units.number
            units_currency = posting.units.currency
            if gross:
                rebate = self._rebate_sums.get(id(bean_txn), {}).get(units_currency)
                amount_ok = bool(rebate) and self._amount_matches(
                    txn, abs(units_number) + rebate, units_currency, None
                )
            else:
                amount_ok = self._amount_matches(
                    txn,
                    units_number,
                    units_currency,
                    posting.price if by_cost else None,
                ) or self._fallback_amount_matches(txn, units_number, units_currency)
            if not amount_ok:
                return False

            # Check amount sign matches the expected direction for Asset/Liability accounts
            # Statement: negative = income (money in), positive = expense (money out)
            # Asset posting: positive = debit (money in), negative = credit (money out)
            # So signs should be OPPOSITE for a valid match
            if posting.account.startswith("Assets:"):
                # For assets: statement income (-) should match asset inflow (+)
                #             statement expense (+) should match asset outflow (-)
                stmt_is_income = txn.amount < 0
                posting_is_inflow = units_number > 0
                if stmt_is_income != posting_is_inflow:
                    return False
            elif posting.account.startswith("Liabilities:"):
                # For liabilities (credit cards): credits are negative, debits are positive
                # Statement expense (+) should match liability credit (-) = using credit card
                # Statement income (-) should match liability debit (+) = refund to credit card
                stmt_is_expense = txn.amount > 0
                posting_is_credit = units_number < 0
                if stmt_is_expense != posting_is_credit:
                    return False

        # Date must be within tolerance
        date_diff = abs((txn.date - bean_txn.date).days)
        if date_diff > self.config.date_tolerance:
            return False

        # Card suffix hard-filter is only active on the legacy path. With
        # meta_check on, mismatches surface via _diagnose_meta instead.
        if not meta_check and txn.card_last4:
            meta_card = _read_card_last4(entry)
            if meta_card and meta_card != txn.card_last4:
                return False

        return True

    def _amount_matches(
        self,
        txn: Transaction,
        units_number: Decimal,
        units_currency: str,
        price: Amount | None,
    ) -> bool:
        """Compare the billed amount against the posting's units or its cost.

        The cost counts only in the price's own currency: an exchange leg
        `-630.00 CNY @@ 90.00 USD` is not a 90 USD payment.
        """
        tolerance = self.config.amount_tolerance
        if units_currency == txn.currency and (
            abs(abs(txn.amount) - abs(units_number)) <= tolerance
        ):
            return True
        if price is None or price.number is None or price.currency != txn.currency:
            return False
        return abs(abs(txn.amount) - abs(units_number * price.number)) <= tolerance

    def _fallback_amount_matches(
        self, txn: Transaction, units_number: Decimal, units_currency: str
    ) -> bool:
        return self._original_amount_matches(
            txn, units_number, units_currency
        ) or self._net_of_fee_matches(txn, units_number, units_currency)

    def _net_of_fee_matches(
        self, txn: Transaction, units_number: Decimal, units_currency: str
    ) -> bool:
        """Accept an outflow booked at the amount that arrived, fee left out.

        Hand-written ledgers often record a fee-bearing transfer with the net
        figure on both legs, as bean-sieve itself did before it posted fees.
        """
        net = _net_of_fee(txn)
        if net is None or units_currency != txn.currency:
            return False
        return abs(net - abs(units_number)) <= self.config.amount_tolerance

    def _original_amount_matches(
        self, txn: Transaction, units_number: Decimal, units_currency: str
    ) -> bool:
        """Compare a foreign transaction's original amount against the posting.

        bean-sieve 0.7.0 and earlier wrote the original amount as the card
        posting: BOCOM with its original currency (`20.00 HKD`), CMB labelled
        as the billed currency (`20.00 CNY`), since its statement gives no
        original currency. Accepting both keeps those ledgers matching.
        """
        if txn.original_amount is None:
            return False
        if units_currency != (txn.original_currency or txn.currency):
            return False
        diff = abs(txn.original_amount - abs(units_number))
        return diff <= self.config.amount_tolerance

    def _diagnose_ambiguous(
        self, txn: Transaction, chosen: TxnPosting, n_others: int
    ) -> MatchDiagnostic:
        file, line, account = _entry_location(chosen)
        bean_txn = chosen.txn
        payee = bean_txn.payee or bean_txn.narration or ""
        message = (
            f"Ambiguous match: {txn.date} {txn.amount} {txn.currency} matched "
            f"{account} ({payee}); {n_others} other same-date/amount candidate(s); "
            "statement not constrained to a target account; configure an "
            "`accounts` mapping for this payment method to disambiguate"
        )
        return MatchDiagnostic(
            file=file,
            line=line,
            chosen_account=account,
            alternatives=n_others,
            message=message,
        )

    def _diagnose_meta(
        self, txn: Transaction, entry: TxnPosting
    ) -> MetaDiagnostic | None:
        if not txn.card_last4:
            return None
        meta_card = _read_card_last4(entry)
        if meta_card == txn.card_last4:
            return None

        file, line, account = _entry_location(entry)
        expected = txn.card_last4

        if meta_card is None:
            severity = "hint"
            message = (
                f"{file}:{line}  hint  missing posting meta "
                f'`card_last4: "{expected}"` on {account}'
            )
        else:
            severity = "warn"
            message = (
                f"{file}:{line}  warn  posting meta `card_last4` mismatch on "
                f'{account}: ledger "{meta_card}", statement "{expected}"'
            )
        return MetaDiagnostic(
            severity=severity,
            file=file,
            line=line,
            account=account,
            key="card_last4",
            expected=expected,
            actual=meta_card,
            message=message,
        )


def _balance_key(posting: Posting) -> tuple[str, str | None]:
    return posting.account, posting.units.currency if posting.units else None


def _amounts_by_currency(posting: Posting) -> dict[str, Decimal]:
    """The units, plus the weight Beancount balances the posting at: the
    total cost of a `{}` lot, else the total price of `@` / `@@`."""
    units = posting.units
    if units is None or units.number is None:
        return {}
    amounts = {units.currency: units.number}
    weight = get_weight(posting)
    if isinstance(weight.number, Decimal):
        amounts[weight.currency] = weight.number
    return amounts


def _income_statement_sums(txn: BeanTransaction) -> dict[str, Decimal]:
    """Per-currency total of the Expenses/Income postings, such as a fee or a
    rebate booked beside a transfer."""
    sums: dict[str, Decimal] = {}
    for posting in txn.postings:
        if not posting.account.startswith(("Expenses:", "Income:")):
            continue
        for currency, number in _amounts_by_currency(posting).items():
            sums[currency] = sums.get(currency, Decimal(0)) + number
    return sums


def _has_gross_fallback(txn: Transaction) -> bool:
    return bool(txn.metadata.get(REBATE_TOPUP_MATCH))


def _net_of_fee(txn: Transaction) -> Decimal | None:
    """Amount an outflow delivered after its fee; inflows already report it."""
    if not txn.fee or txn.amount <= 0:
        return None
    return txn.amount - txn.fee


def _is_rebate_account(account: str, prefixes: Iterable[str]) -> bool:
    """Whether account is one of prefixes or a sub-account of one.

    A trailing colon is ignored, so ``Income:Rebate:`` and ``Income:Rebate``
    both cover ``Income:Rebate`` and every ``Income:Rebate:*`` account.
    """
    for prefix in prefixes:
        base = prefix.rstrip(":")
        if account == base or account.startswith(base + ":"):
            return True
    return False


def _rebate_sums(entry: BeanTransaction, prefixes: Iterable[str]) -> dict[str, Decimal]:
    # Income postings are negative when earned, so negating them lets a
    # reversal posting reduce the gross rather than add to it.
    sums: dict[str, Decimal] = {}
    for posting in entry.postings:
        if not _is_rebate_account(posting.account, prefixes):
            continue
        if posting.units is None or posting.units.number is None:
            continue
        currency = posting.units.currency
        sums[currency] = sums.get(currency, Decimal(0)) - posting.units.number
    return sums


def _entry_location(entry: TxnPosting) -> tuple[str, int, str]:
    """Return (filename, lineno, account) for a ledger posting."""
    bean_txn = entry.txn
    file = bean_txn.meta.get("filename", "<unknown>")
    line = bean_txn.meta.get("lineno") or 0
    return file, line, entry.posting.account


def _read_card_last4(entry: TxnPosting) -> str | None:
    """Read card_last4 metadata, preferring posting-level over transaction-level."""
    posting_meta = entry.posting.meta or {}
    value = posting_meta.get("card_last4")
    if value is None:
        value = entry.txn.meta.get("card_last4")
    return str(value) if value is not None else None


def create_sieve(
    ledger_path: Path,
    account_filter: str | None = None,
    date_range: tuple[date, date] | None = None,
    date_tolerance: int = 2,
) -> Sieve:
    """
    Create and initialize a Sieve engine.

    Convenience function for common usage.
    """
    config = SieveConfig(date_tolerance=date_tolerance)
    sieve = Sieve(config)
    sieve.load_ledger(ledger_path, account_filter, date_range)
    return sieve
